        <div class="w3-panel w3-white">
            <p>Alweer een tijdje terug heb ik sommige deelnemers van afgelopen zomer gevraagd of ze zin zouden hebben om het slotconcert van de La Pellegrina barokcursus in Nieuw Sion met barokmuziek uit Centraal Europa te herhalen. Daar werd enthousiast op gereageerd. We kunnen nu het programma hernemen op <strong>zaterdagavond 16 januari in de Dorpskerk in Beusichem</strong>. Femke werkt weer met het orkest en speelt mee als concertmeester. Dirkjan werkt met de solisten en het koor en dirigeert het geheel.</p>
            <p>We hopen natuurlijk dat je kunt en wilt meedoen. <strong>Meld je in dat geval vandaag nog aan!</strong> Je kunt je opgeven via <a href="https://forms.gle/KqTRvZPeJ3Vi6CpS7" target="_blank">dit aanmeldformulier</a>. Laat graag vóór 15 oktober iets van je horen. Begin november hoor je of het project doorgaat. Mocht je nog een voorbehoud hebben, dan toch graag even laten weten via <a href="mailto:dirkjan@pellegrina.net">dirkjan@pellegrina.net</a>.</p>
            <p>Er is waarschijnlijk een prima basisbezetting, maar we hebben naast de reünisten nog extra mensen nodig. Er is dus ook plaats voor extra zangers en bespelers van 415-instrumenten, met name strijkers. Schroom ook vooral niet om deze informatie door te sturen naar andere goede en mogelijk belangstellende instrumentalisten en koorzangers.</p>
            <h2 class="w3-center w3-flat-belize-hole">Repetitieschema</h2>
            <ul>
                <li>zaterdag 9 januari: repetitie middag (en eventueel avond) op afspraak bij Dirkjan thuis in Utrecht, voor zangers, BC en Dirkjan</li>
                <li>vrijdag 15 januari, 14:00 - max. 21:00: repetitie in de Oud-Katholieke Kerk Culemborg; eerst zangers met Dirkjan en orkest met Femke, na de pauze gezamenlijk</li>
                <li>zaterdag 16 januari: 16:00 generale repetitie en 20:00 concert, beide in de Dorpskerk in Beusichem, Markt 1</li>
            </ul>
            <p>De kosten voor deelname aan dit project bedragen € 95 p.p. De deelnemersbijdrage hoeft pas betaald te worden na bevestiging van plaatsing.</p>
