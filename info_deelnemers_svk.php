                <p>
                    De koorrepetities staan onder leiding van Mitchell Sandler, die ook de
                    bassolo's zal zingen. De solisten van afgelopen zomer, Karolína Janů en
                    Martin Slavík, zijn ook weer van de partij. De orkestrepetities en het
                    geheel staan onder leiding van
                    <a href="https://www.horringa.net" target="_blank">
                        Dirkjan Horringa
                    </a>
                    . Petr, Martina en hun zoons en andere Tsjechische Pellegrina-docenten
                    komen weer over en spelen mee. Ook komen er enkele Tsjechische
                    koorzangers uit Budějovice over om te helpen met de uitspraak.
                </p>
