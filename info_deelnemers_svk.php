                <p>
                    Wat liep onze laatste cursus in České Budějovice fijn! En wat speelden en zongen we een fantastisch werk:
                    Dvořáks cantate
                    <strong>Het Bruidshemd</strong>
                    , oftewel
                    <em>Svatební košile</em>
                    .
                    De klanken van koor, orkest en solisten spetterden door de kathedraal en wisten het publiek mee te slepen.
                    Helaas konden we dit programma maar eenmaal opvoeren en is de opname door een fout mislukt.
                    De roep om het werk nog een keer uit te voeren, maar dan in Nederland, werd hoorbaar.
                </p>
                <p>
                    Op zondagmiddag 28 februari 2026 voeren we dit prachtige werk opnieuw uit in de Geertekerk te Utrecht.
                    We hopen op een zo groot mogelijke deelname van de deelnemers van afgelopen zomer.
                    Omdat waarschijnlijk niet iedereen kan meedoen, doen we ook een beroep op Pellegrina-deelnemers van andere cursussen en jaren,
                    en op andere goede en belangstellende koorzangers en instrumentalisten, met name strijkers.
                </p>
                <p>
                    Voor verdere en actuele informatie kun je ook terecht op
                    <a href="https://projectorkest.pellegrina.net/info_deelnemers_svk.php">projectorkest.pellegrina.net</a>
